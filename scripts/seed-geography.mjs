import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const args = process.argv.slice(2).filter((value) => !value.startsWith('--'));
const connection = process.env.DATABASE_URL;
const sqlMode = process.argv.includes('--sql') || !connection;

if (!sqlMode && !connection) {
  console.error('Set DATABASE_URL (your Neon connection string) or pass --sql to write a SQL file.');
  process.exit(1);
}

const file = args[0] ?? 'scripts/geography.json';
const output = args[1] ?? 'database/geography-seed.sql';
const source = 'https://raw.githubusercontent.com/dr5hn/countries-states-cities-database/master/json/countries+states+cities.json';

if (!existsSync(file)) {
  console.log(`Downloading ${source} ...`);
  const response = await fetch(source);
  if (!response.ok) throw new Error(`Download failed: ${response.status}`);
  writeFileSync(file, Buffer.from(await response.arrayBuffer()));
}

const data = JSON.parse(readFileSync(file, 'utf8'));

const countryRows = [];
const stateRows = [];
const cityRows = [];
const stateKeys = new Set();
const cityKeys = new Set();

for (const country of data) {
  countryRows.push([country.iso2, country.name, country.nationality ?? '', String(country.phonecode ?? '')]);
  for (const state of country.states ?? []) {
    const stateCode = String(state.iso3166_2 || state.iso2 || state.id);
    const stateKey = `${country.iso2}|${stateCode}`;
    if (!stateKeys.has(stateKey)) {
      stateKeys.add(stateKey);
      stateRows.push([country.iso2, stateCode, state.name]);
    }
    for (const city of state.cities ?? []) {
      const cityKey = `${stateKey}|${city.name}`;
      if (cityKeys.has(cityKey)) continue;
      cityKeys.add(cityKey);
      cityRows.push([country.iso2, stateCode, city.name]);
    }
  }
}

const COUNTRY_COLUMNS = ['code', 'name', 'nationality', 'phonecode'];
const STATE_COLUMNS = ['country_code', 'code', 'name'];
const CITY_COLUMNS = ['country_code', 'state_code', 'name'];

function sqlText(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertStatements(table, columns, rows, chunk = 1000) {
  const statements = [];
  for (let start = 0; start < rows.length; start += chunk) {
    const slice = rows.slice(start, start + chunk);
    const values = slice.map((row) => `  (${row.map(sqlText).join(', ')})`).join(',\n');
    statements.push(`INSERT INTO public.${table} (${columns.join(', ')}) VALUES\n${values}\nON CONFLICT DO NOTHING;`);
  }
  return statements.join('\n\n');
}

const schemaStatements = [
  'CREATE TABLE IF NOT EXISTS public.hotelx_country (code text PRIMARY KEY, name text NOT NULL UNIQUE, nationality text NOT NULL DEFAULT \'\', phonecode text NOT NULL DEFAULT \'\');',
  'ALTER TABLE public.hotelx_country ADD COLUMN IF NOT EXISTS nationality text NOT NULL DEFAULT \'\';',
  'ALTER TABLE public.hotelx_country ADD COLUMN IF NOT EXISTS phonecode text NOT NULL DEFAULT \'\';',
  'CREATE TABLE IF NOT EXISTS public.hotelx_state (country_code text NOT NULL REFERENCES public.hotelx_country(code) ON DELETE CASCADE, code text NOT NULL, name text NOT NULL, PRIMARY KEY(country_code, code));',
  'CREATE TABLE IF NOT EXISTS public.hotelx_city (country_code text NOT NULL, state_code text NOT NULL, name text NOT NULL, PRIMARY KEY(country_code, state_code, name), FOREIGN KEY(country_code, state_code) REFERENCES public.hotelx_state(country_code, code) ON DELETE CASCADE);',
  'CREATE INDEX IF NOT EXISTS hotelx_city_state_idx ON public.hotelx_city(country_code, state_code);',
  'DELETE FROM public.hotelx_city;',
  'DELETE FROM public.hotelx_state;',
  'DELETE FROM public.hotelx_country;',
];
const header = [
  '-- HotelX global geography seed. Generated by scripts/seed-geography.mjs.',
  '-- Run once in the Neon SQL editor, or: psql "$DATABASE_URL" -f <file>.',
];

if (process.argv.includes('--split')) {
  const dir = args[1] ?? 'database/geography-seed';
  mkdirSync(dir, { recursive: true });
  const files = [
    ['00-schema.sql', [...header, '-- Run this file first.', '', ...schemaStatements].join('\n')],
    ['01-countries.sql', [...header, '', insertStatements('hotelx_country', COUNTRY_COLUMNS, countryRows)].join('\n')],
    ['02-states.sql', [...header, '', insertStatements('hotelx_state', STATE_COLUMNS, stateRows)].join('\n')],
  ];
  const chunk = 15000;
  for (let start = 0; start < cityRows.length; start += chunk) {
    const index = String(start / chunk + 1).padStart(2, '0');
    files.push([`03-cities-${index}.sql`, [...header, '', insertStatements('hotelx_city', CITY_COLUMNS, cityRows.slice(start, start + chunk))].join('\n')]);
  }
  let total = 0;
  for (const [name, body] of files) {
    writeFileSync(join(dir, name), body);
    total += body.length;
  }
  console.log(`Wrote ${files.length} files to ${dir}/ (${(total / 1024 / 1024).toFixed(1)} MB): ${countryRows.length} countries, ${stateRows.length} states, ${cityRows.length} cities.`);
  console.log(`Run them in order (00, 01, 02, then 03-cities-*). Or one shot: psql "$DATABASE_URL" -f ${output}`);
  process.exit(0);
}

if (sqlMode) {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, [
    ...header,
    '',
    ...schemaStatements,
    '',
    insertStatements('hotelx_country', COUNTRY_COLUMNS, countryRows),
    insertStatements('hotelx_state', STATE_COLUMNS, stateRows),
    insertStatements('hotelx_city', CITY_COLUMNS, cityRows),
    '',
  ].join('\n'));
  const size = readFileSync(output).length;
  console.log(`Wrote ${output} (${(size / 1024 / 1024).toFixed(1)} MB): ${countryRows.length} countries, ${stateRows.length} states, ${cityRows.length} cities.`);
  console.log('Run it in the Neon SQL editor, or with: psql "$DATABASE_URL" -f ' + output);
  process.exit(0);
}

const host = new URL(connection).hostname.replace(/-pooler$/, '');
const endpoint = `https://${host}/sql`;

async function run(query, params = []) {
  const response = await fetch(endpoint, {
    method: 'POST',
    redirect: 'manual',
    headers: {
      'Content-Type': 'application/json',
      'Neon-Connection-String': connection,
      'Neon-Array-Mode': 'true',
      'Neon-Raw-Text-Output': 'true',
    },
    body: JSON.stringify({ query, params }),
  });
  if (!response.ok) throw new Error(`Neon ${response.status}: ${await response.text()}`);
  return response.json();
}

async function insertRows(table, columns, rows, chunk = 500) {
  for (let start = 0; start < rows.length; start += chunk) {
    const slice = rows.slice(start, start + chunk);
    const values = slice
      .map((_, row) => `(${columns.map((__, col) => `$${row * columns.length + col + 1}`).join(', ')})`)
      .join(', ');
    await run(`INSERT INTO public.${table} (${columns.join(', ')}) VALUES ${values} ON CONFLICT DO NOTHING`, slice.flat());
    process.stdout.write(`\r${table}: ${Math.min(start + chunk, rows.length)}/${rows.length}`);
  }
  process.stdout.write('\n');
}

console.log('Clearing existing geography ...');
await run('DELETE FROM public.hotelx_city');
await run('DELETE FROM public.hotelx_state');
await run('DELETE FROM public.hotelx_country');

await insertRows('hotelx_country', COUNTRY_COLUMNS, countryRows);
await insertRows('hotelx_state', STATE_COLUMNS, stateRows);
await insertRows('hotelx_city', CITY_COLUMNS, cityRows);
console.log(`Done: ${countryRows.length} countries, ${stateRows.length} states, ${cityRows.length} cities.`);
